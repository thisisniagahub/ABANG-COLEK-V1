function form(page: Page, title: string) { return page.locator('.xp-form-panel').filter({ has: page.getByRole('heading', { name: title, exact: true }) }); }
async function submit<T>(page: Page, target: Locator, button: string, path: string): Promise<T> {
  const received = page.waitForResponse(response => new URL(response.url()).pathname === `/api/platform${path}` && response.request().method() === 'POST');
  await target.getByRole('button', { name: button, exact: true }).click();
  const response = await received, result = await response.json();
  expect(response.ok(), `${path}: ${result.code ?? 'request failed'}`).toBe(true);
  expect(result.ok).toBe(true);
  return result.data as T;
}
async function upload(page: Page, entityId: string, name: string, content: string) {
  const session = await (await page.request.get('/api/platform/session')).json();
  const response = await page.request.post('/api/platform/evidence/upload', { headers: { Origin: fixture().origin, 'X-CSRF-Token': session.data.csrfToken }, multipart: { entityId, file: { name, mimeType: 'text/plain', buffer: Buffer.from(content) } } });
  const result = await response.json();
  expect(response.ok(), `Actual file upload: ${result.code ?? 'request failed'}`).toBe(true);
  expect(result.data.kind).toBe('file');
  expect(result.data.size).toBe(Buffer.byteLength(content));
  return result.data as { id: string; sha256: string };
}
function localInput(stamp: Date) { return new Date(stamp.getTime() + 8 * 3600_000).toISOString().slice(0, 16); }
/** Inspect the downloaded archive bytes rather than accepting a successful export request alone. */
function tarContents(input: Buffer): Map<string, Buffer> {
  const bytes = input[0] === 0x1f && input[1] === 0x8b ? gunzipSync(input) : input;
  const result = new Map<string, Buffer>();
  for (let offset = 0; offset + 512 <= bytes.length; ) {
    const header = bytes.subarray(offset, offset + 512);
    if (header.every(byte => byte === 0)) break;
    const name = header.subarray(0, 100).toString('utf8').replace(/\0.*$/, '');
    const size = Number.parseInt(header.subarray(124, 136).toString('ascii').replace(/\0/g, '').trim(), 8);
    expect(Number.isSafeInteger(size) && size >= 0, 'Valid archive member size').toBe(true);
    expect(offset + 512 + size <= bytes.length, 'Complete archive member bytes').toBe(true);
    expect(result.has(name), 'No duplicate archive member can shadow approved bytes').toBe(false);
    result.set(name, bytes.subarray(offset + 512, offset + 512 + size));
    offset += 512 + Math.ceil(size / 512) * 512;
  }
  return result;
}

test('founder marketing UI stores rights, approves exact revision and downloads real manual caption and asset bundle', async ({ page }) => {
  test.setTimeout(90_000);
  await login(page, 'founder');
  await page.goto('/founder/marketing');
  const title = `QA marketing ${crypto.randomUUID()}`, caption = `Isolated QA caption ${title}. No product, pricing or sales claim.`;
  await page.getByRole('button', { name: 'Kempen baharu', exact: true }).click();
  const draftForm = form(page, 'Kempen & Promosi Baharu');
  await draftForm.getByLabel(/Nama kempen/).fill(title);
  await draftForm.getByLabel(/Objektif kempen/).fill('Isolated first-party release journey verification');
  await draftForm.getByLabel(/Caption \/ approved claims draft/).fill(caption);
  const draft = await submit<CampaignRecord>(page, draftForm, 'Simpan draft revision', '/campaigns');
  expect(draft.status).toBe('draft');
  const assetText = `QA-authored owned file for ${title}. Test artifact only; no customer or business claims.`;
  const evidence = await upload(page, draft.id, 'qa-owned-asset.txt', assetText);
  const card = page.locator('.xp-campaign').filter({ has: page.getByRole('heading', { name: title, exact: true }) });
  await card.getByRole('button', { name: 'Edit revision', exact: true }).click();
  const editor = form(page, `Edit ${title}`);
  const assetId = `qa-owned-${draft.id}`;
  await editor.getByLabel('Aset: ID').fill(`${assetId}|QA authored text|Owned test artifact generated by this QA test|No person depicted or personal data|${evidence.id}`);
  const edited = await submit<CampaignRecord>(page, editor, 'Simpan draft revision', `/campaigns/${draft.id}/update`);
  expect(edited.assets[0].evidenceId).toBe(evidence.id);
  const session = await (await page.request.get('/api/platform/session')).json();
  const consentRes = await page.request.post('/api/platform/campaigns/consent', {
    headers: { Origin: fixture().origin, 'X-CSRF-Token': session.data.csrfToken, 'Idempotency-Key': crypto.randomUUID() },
    data: { campaignId: draft.id, assetId, state: 'granted', scope: 'manual_export', evidenceId: evidence.id },
  });
  expect(consentRes.ok()).toBe(true);
  await card.locator('summary').filter({ hasText: 'Assets & rights' }).click();
  await expect(card).toContainText('Owned test artifact');
  await card.getByRole('button', { name: 'Review & approve', exact: true }).click();
  const approvalForm = form(page, `Approve exact revision ${edited.revision}`);
  await approvalForm.getByLabel('Approval expiry (MYT)').fill(localInput(new Date(Date.now() + 3600_000)));
  const approved = await submit<CampaignRecord>(page, approvalForm, 'Sahkan copy, assets & revision', `/campaigns/${draft.id}/approve`);
  expect(approved.copy).toBe(caption);
  expect(approved.revision).toBe(edited.revision + 1);
  await expect(card.locator('.xp-status')).toHaveText('approved');
  const captionDownload = page.waitForEvent('download');
  const captionReceipt = page.waitForResponse(response => new URL(response.url()).pathname === `/api/platform/campaigns/${draft.id}/export` && response.request().method() === 'POST');
  await card.getByRole('button', { name: 'Export caption', exact: true }).click();
  const textDownload = await captionDownload;
  expect(await textDownload.failure()).toBeNull();
  expect(await readFile((await textDownload.path())!, 'utf8')).toBe(caption);
  const textArtifact = (await (await captionReceipt).json()).data as ExportArtifact;
  expect(textArtifact.status).toBe('exported');
  expect(textArtifact.campaignRevision).toBe(approved.revision);
  await expect(card.getByRole('button', { name: 'Download asset bundle', exact: true })).toBeEnabled();
  const bundleDownload = page.waitForEvent('download');
  const bundleReceipt = page.waitForResponse(response => new URL(response.url()).pathname === `/api/platform/campaigns/${draft.id}/export` && response.request().method() === 'POST');
  await card.getByRole('button', { name: 'Download asset bundle', exact: true }).click();
  const downloaded = await bundleDownload;
  expect(await downloaded.failure()).toBeNull();
  const entries = tarContents(await readFile((await downloaded.path())!));
  expect([...entries.keys()].sort()).toEqual(['caption.txt', `${evidence.id}.txt`].sort());
  expect(entries.get('caption.txt')?.toString('utf8')).toBe(caption);
  expect(entries.get(`${evidence.id}.txt`)?.toString('utf8')).toBe(assetText);
  const bundleArtifact = (await (await bundleReceipt).json()).data as ExportArtifact;
  expect(bundleArtifact.fileRefs).toEqual([evidence.id]);
  expect(bundleArtifact.status).toBe('exported');
  expect(bundleArtifact.campaignRevision).toBe(approved.revision);
  await page.reload();
  await expect(card).toContainText(caption);
  await expect(card.locator('.xp-status')).toHaveText('approved');
  await expect(page.getByText('Tiada akaun social connected yang disahkan', { exact: false }).first()).toBeVisible();
});

